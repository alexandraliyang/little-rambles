function Art({ a, tall }) {
  const m = CAT_META[a.cat] || CAT_META.nature;
  /* FB17-01. Resolved DURING the first render, not in an effect. The curated URL
     is known synchronously from IMG[a.id], so setting it in useEffect meant every
     card rendered one frame of the generated fallback before the photo arrived —
     the flash the founder saw each time the deck advanced. Art is keyed by
     activity id at every call site, so the initialiser runs fresh per activity
     and nothing leaks between cards. */
  const [src, setSrc] = useState(() => (!a.userAdded && IMG[a.id] ? unsplash(IMG[a.id]) : null));
  const [failed, setFailed] = useState(false);
  const h = hash(a.id);
  /* FB4-04. Curated first, Commons only as a fallback — this order was inverted.
     All 155 activities carry a hand-picked IMG id, so the keyword search was
     overriding a known-good photo on every single card, and its misses are what
     the founder saw: illustrations, and images not obviously about small
     children. A hand-picked photo cannot regress; a search result can. Commons
     now only serves activities with no curated image, which today means none of
     the built-in set and only future or imported ones. */
  useEffect(() => {
    /* FB7-01. React reuses this component's slot as the deck advances, so the
       PREVIOUS activity's `failed`/`src` survive into the next one unless they
       are cleared here. One broken photo therefore poisoned the slot: every
       later card rendered GenArt, which is why a run of cards all turned into
       illustrations even though their own photos were fine. Reset first, then
       resolve. */
    setFailed(false);
    if (a.userAdded) return;                 // FB2-16: never look one up for your own places
    if (IMG[a.id]) return;                   // already resolved synchronously above
    let live = true;
    findPhoto(a)
      .then((u) => { if (!live) return; if (u) setSrc(u); else setFailed(true); })
      .catch(() => { if (!live) return; setFailed(true); });
    return () => { live = false; };
  }, [a.id]);
  if (a.userAdded) return <div className={"art mineart" + (tall ? " tall" : "")}>
    <MineArt /><span className="ae">{a.emoji}</span><span className="minetag">💜 Yours</span>
  </div>;
  return <div className={"art" + (tall ? " tall" : "")}>
    {src && !failed ? <img src={src} alt="" loading="lazy" draggable={false} onError={() => { if (IMG[a.id] && src.indexOf("unsplash") < 0) setSrc(unsplash(IMG[a.id])); else setFailed(true); }} /> : <GenArt a={a} m={m} h={h} />}
    <span className="ae">{a.emoji}</span>
  </div>;
}
