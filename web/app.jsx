function tint(hex, amt) {
  const n = parseInt(hex.slice(1), 16), cl = (x) => Math.max(0, Math.min(255, x));
  return "#" + ((1 << 24) + (cl((n >> 16) + amt) << 16) + (cl(((n >> 8) & 255) + amt) << 8) + cl((n & 255) + amt)).toString(16).slice(1);
}
